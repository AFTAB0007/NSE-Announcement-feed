def _today_utc_str() -> str:
    return datetime.now(timezone.utc).date().isoformat()


def _load_json_safe(path: str) -> dict:
    if not os.path.exists(path):
        return {}
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except (json.JSONDecodeError, OSError):
        return {}


def _save_json_atomic(path: str, data: dict) -> None:
    tmp_path = path + ".tmp"
    try:
        with open(tmp_path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        os.replace(tmp_path, path)
    except OSError as e:
        log(f"❌ Failed to save {path}: {e}")


def gemini_calls_used_today() -> int:
    return _load_json_safe(GEMINI_USAGE_PATH).get(_today_utc_str(), 0)


def record_gemini_call() -> None:
    usage = _load_json_safe(GEMINI_USAGE_PATH)
    today = _today_utc_str()
    usage[today] = usage.get(today, 0) + 1
    usage = {d: c for d, c in usage.items() if d == today}
    _save_json_atomic(GEMINI_USAGE_PATH, usage)


def gemini_budget_remaining() -> int:
    return max(0, GEMINI_DAILY_CALL_BUDGET - gemini_calls_used_today())


def _is_quota_exhausted(e: Exception) -> bool:
    text = str(e).upper().replace("_", "")
    return "RESOURCEEXHAUSTED" in text or "429" in text


def _is_transient_error(e: Exception) -> bool:
    text = str(e).upper()
    return any(m in text for m in ("503", "UNAVAILABLE", "TIMEOUT", "DEADLINE"))


def resolve_gemini_model(force: bool = False) -> bool:
    global MODEL_NAME, _last_model_resolution_attempt

    if MODEL_NAME is not None:
        return True

    now = time.time()
    if not force and (now - _last_model_resolution_attempt) < GEMINI_RESOLUTION_COOLDOWN_SECONDS:
        return False
    _last_model_resolution_attempt = now

    if gemini_budget_remaining() <= 0:
        log("🛑 Daily Gemini call budget used up.")
        return False

    keys_tested = 0
    total_keys = max(1, len(GEMINI_KEYS_POOL))

    while keys_tested < total_keys:
        try:
            client = get_genai_client()
        except Exception as e:
            log(f"❌ Client initialization failed: {e}")
            return False

        for candidate in GEMINI_MODEL_CANDIDATES:
            try:
                record_gemini_call()
                response = client.models.generate_content(model=candidate, contents="Reply with: OK")
                MODEL_NAME = candidate
                log(f"✅ Connected to Gemini model '{candidate}' using Key index {ACTIVE_KEY_INDEX + 1}")
                return True
            except Exception as e:
                if _is_quota_exhausted(e):
                    log(f"⚠️ Key index {ACTIVE_KEY_INDEX + 1} quota hit during model test.")
                    rotate_gemini_key("Quota during resolution")
                    break
                continue

        keys_tested += 1

    log("❌ Could not resolve any Gemini candidate model across available keys.")
    return False


