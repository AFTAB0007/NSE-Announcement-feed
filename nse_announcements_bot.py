_NSE_EQUITY_MASTER = {}


def _company_match_text(value: str) -> str:
    """Normalize company names for conservative exact-phrase matching."""
    value = (value or "").upper()
    value = re.sub(r"&", " AND ", value)
    value = re.sub(r"[^A-Z0-9]+", " ", value)
    return re.sub(r"\s+", " ", value).strip()


def get_nse_equity_master(force_refresh: bool = False) -> dict:
    """Return {official_symbol: official_company_name}; cache CSV for 24 hours."""
    global _NSE_EQUITY_MASTER
    if _NSE_EQUITY_MASTER and not force_refresh:
        return _NSE_EQUITY_MASTER

    headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/120 Safari/537.36",
        "Accept": "text/csv,*/*",
        "Referer": "https://www.nseindia.com/",
    }
    csv_text = ""
    try:
        cache_is_fresh = (
            os.path.exists(NSE_EQUITY_MASTER_PATH)
            and (time.time() - os.path.getmtime(NSE_EQUITY_MASTER_PATH)) < NSE_EQUITY_MASTER_MAX_AGE_SECONDS
        )
        if cache_is_fresh and not force_refresh:
            with open(NSE_EQUITY_MASTER_PATH, "r", encoding="utf-8-sig", newline="") as f:
                csv_text = f.read()

        if not csv_text:
            for url in NSE_EQUITY_MASTER_URLS:
                try:
                    response = requests.get(url, headers=headers, timeout=20)
                    if response.status_code == 200 and "SYMBOL" in response.text.upper() and "COMPANY" in response.text.upper():
                        csv_text = response.content.decode("utf-8-sig", errors="replace")
                        tmp_path = NSE_EQUITY_MASTER_PATH + ".tmp"
                        with open(tmp_path, "w", encoding="utf-8-sig", newline="") as f:
                            f.write(csv_text)
                        os.replace(tmp_path, NSE_EQUITY_MASTER_PATH)
                        break
                except requests.RequestException:
                    continue

        if not csv_text:
            log("⚠️ Official NSE equity master unavailable; symbol validation cannot be guaranteed.")
            return _NSE_EQUITY_MASTER

        rows = csv.DictReader(csv_text.splitlines())
        master = {}
        for row in rows:
            symbol = (row.get("SYMBOL") or "").strip().upper()
            company = (row.get("NAME OF COMPANY") or row.get("NAME_OF_COMPANY") or "").strip()
            series = (row.get(" SERIES") or row.get("SERIES") or "").strip().upper()
            if symbol and company and (not series or series == "EQ"):
                master[symbol] = company

        if master:
            _NSE_EQUITY_MASTER = master
            log(f"✅ Official NSE equity master loaded: {len(master)} symbols.")
        else:
            log("⚠️ NSE equity master response parsed but contained no valid symbols.")
    except Exception as e:
        log(f"⚠️ NSE equity master load failed: {e}")

    return _NSE_EQUITY_MASTER


def resolve_official_nse_symbol(announcement_text: str, equity_master: dict = None) -> str:
    """Resolve only a unique official company-name phrase; never infer from PDF prefix."""
    master = equity_master if equity_master is not None else get_nse_equity_master()
    text = _company_match_text(announcement_text)
    if not text or not master:
        return ""

    matches = []
    for symbol, company in master.items():
        company_norm = _company_match_text(company)
        if len(company_norm) < 5:
            continue
        if re.search(r"(?<![A-Z0-9])" + re.escape(company_norm) + r"(?![A-Z0-9])", text):
            matches.append((len(company_norm), symbol))

    if not matches:
        return ""
    longest = max(length for length, _ in matches)
    best_symbols = {symbol for length, symbol in matches if length == longest}
    return next(iter(best_symbols)) if len(best_symbols) == 1 else ""


def is_official_nse_symbol(symbol: str, equity_master: dict = None) -> bool:
    master = equity_master if equity_master is not None else get_nse_equity_master()
    candidate = normalize_symbol(symbol)
    return bool(candidate and candidate in master)


def init_fo_database() -> None:
    with sqlite3.connect(FO_DB_PATH) as conn:
        cursor = conn.cursor()
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS fno_stocks (
                symbol TEXT PRIMARY KEY,
                company_name TEXT,
                lot_size INTEGER,
                updated_at TEXT
            )
        """)
        cursor.execute("CREATE INDEX IF NOT EXISTS idx_fno_sym ON fno_stocks(symbol)")
        cursor.execute("CREATE INDEX IF NOT EXISTS idx_fno_cmp ON fno_stocks(company_name)")
        conn.commit()


def sync_fo_data_to_db() -> int:
    init_fo_database()
    records_to_insert = []
    now_iso = datetime.now(timezone.utc).isoformat()

    if os.path.exists(FO_CSV_PATH):
        try:
            with open(FO_CSV_PATH, mode="r", encoding="utf-8-sig") as f:
                reader = csv.DictReader(f)
                for row in reader:
                    symbol = (row.get("Symbol") or "").strip().upper()
                    company = (row.get("All Companies") or "").strip().upper()
                    lot_val = None
                    for key in row.keys():
                        if "Lot Size" in key and row[key] and str(row[key]).strip().isdigit():
                            lot_val = int(row[key].strip())
                            break
                    if symbol and lot_val is not None:
                        records_to_insert.append((symbol, company, lot_val, now_iso))
            log(f"📂 Loaded {len(records_to_insert)} F&O contracts from '{FO_CSV_PATH}'.")
        except Exception as e:
            log(f"⚠️ Error reading local F&O CSV: {e}")

    for sym, (comp, lot) in BUILTIN_FO_CATALOG.items():
        records_to_insert.append((sym, comp.upper(), lot, now_iso))

    with sqlite3.connect(FO_DB_PATH) as conn:
        cursor = conn.cursor()
        cursor.executemany("""
            INSERT INTO fno_stocks (symbol, company_name, lot_size, updated_at)
            VALUES (?, ?, ?, ?)
            ON CONFLICT(symbol) DO UPDATE SET
                company_name=excluded.company_name,
                lot_size=excluded.lot_size,
                updated_at=excluded.updated_at
        """, records_to_insert)
        conn.commit()
        cursor.execute("SELECT COUNT(*) FROM fno_stocks")
        total_count = cursor.fetchone()[0]

    log(f"📦 Total F&O records indexed in SQLite ({FO_DB_PATH}): {total_count}")
    return total_count


