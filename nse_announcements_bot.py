def fetch_nse_announcements(max_retries: int = 3) -> list:
    session = get_nse_session()
    if session is None:
        return []

    rss_headers = {
        "Accept": "application/xml,text/xml,*/*",
        "Referer": "https://www.nseindia.com/",
        "Sec-Fetch-Dest": "empty",
        "Sec-Fetch-Mode": "cors",
        "Sec-Fetch-Site": "same-site",
    }

    for attempt in range(1, max_retries + 1):
        try:
            resp = session.get(NSE_RSS_URL, headers=rss_headers, timeout=25)

            if resp.status_code in (401, 403):
                refresh_nse_session()
                session = get_nse_session()
                time.sleep(2)
                continue

            if resp.status_code != 200:
                time.sleep(2)
                continue

            root = ET.fromstring(resp.content)
            announcements = []

            for item in root.findall(".//item"):
                title = (item.findtext("title") or "").strip()
                desc = (item.findtext("description") or "").strip()
                link = (item.findtext("link") or "").strip()
                pub_date = (item.findtext("pubDate") or "").strip()
                symbol_hint = _extract_initial_symbol_hint(title, link)

                announcements.append({
                    "symbol": symbol_hint,
                    "desc": f"{title} | {desc}",
                    "an_dt": pub_date,
                    "attchmntFile": link,
                })

            log(f"Fetched {len(announcements)} announcement(s) directly from NSE RSS XML.")
            return announcements

        except ET.ParseError:
            return []
        except Exception:
            time.sleep(2)

    return []


