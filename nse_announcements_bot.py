def get_current_gemini_key() -> str:
    global ACTIVE_KEY_INDEX
    if not GEMINI_KEYS_POOL:
        return ""
    return GEMINI_KEYS_POOL[ACTIVE_KEY_INDEX % len(GEMINI_KEYS_POOL)]


def rotate_gemini_key(reason: str = "Quota Exhausted") -> bool:
    global ACTIVE_KEY_INDEX, _genai_client
    if len(GEMINI_KEYS_POOL) <= 1:
        log(f"⚠️ Only 1 Gemini Key configured; cannot rotate. Reason: {reason}")
        return False

    old_index = ACTIVE_KEY_INDEX
    ACTIVE_KEY_INDEX = (ACTIVE_KEY_INDEX + 1) % len(GEMINI_KEYS_POOL)
    _genai_client = None
    log(f"🔀 Switched Gemini Key [{old_index + 1}/{len(GEMINI_KEYS_POOL)}] -> [{ACTIVE_KEY_INDEX + 1}/{len(GEMINI_KEYS_POOL)}] ({reason})")
    return True


_genai_client = None


def get_genai_client():
    global _genai_client
    if _genai_client is None:
        key = get_current_gemini_key()
        if not key:
            raise ValueError("No Gemini API key available.")
        _genai_client = genai.Client(api_key=key)
    return _genai_client


