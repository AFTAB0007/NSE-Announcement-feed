def _fetch_from_yfinance(symbol: str):
    try:
        clean_symbol = normalize_symbol(symbol)
        ticker = yf.Ticker(f"{clean_symbol}.NS")
        fast_info = getattr(ticker, "fast_info", None)

        price = None
        pchange = None

        if fast_info:
            price = fast_info.last_price
            prev_close = fast_info.previous_close
            if price is not None and prev_close:
                pchange = ((price - prev_close) / prev_close) * 100.0

        if price is None:
            hist = ticker.history(period="2d")
            if not hist.empty:
                price = float(hist["Close"].iloc[-1])
                if len(hist) > 1:
                    prev_close = float(hist["Close"].iloc[-2])
                    pchange = ((price - prev_close) / prev_close) * 100.0
                else:
                    pchange = 0.0

        if price is not None:
            return float(price), float(pchange if pchange is not None else 0.0)
    except Exception:
        pass
    return None, None


def _fetch_from_google_finance(symbol: str):
    try:
        clean_symbol = normalize_symbol(symbol)
        url = f"https://www.google.com/finance/quote/{clean_symbol}:NSE"
        headers = {"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36"}
        r = requests.get(url, headers=headers, timeout=10)
        if r.status_code == 200:
            price_match = re.search(r'data-last-price="([\d\.,]+)"', r.text)
            if price_match:
                price = float(price_match.group(1).replace(",", ""))
                pchange = 0.0
                change_match = re.search(r'data-last-normal-market-change-percentage="([-+\d\.,]+)"', r.text)
                if change_match:
                    pchange = float(change_match.group(1).replace(",", "").replace("%", ""))
                return price, pchange
    except Exception:
        pass
    return None, None


def fetch_live_quote(symbol: str):
    price, pchange = _fetch_from_yfinance(symbol)
    if price is not None:
        return price, pchange
    price, pchange = _fetch_from_google_finance(symbol)
    return price, pchange


