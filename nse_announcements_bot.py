def normalize_symbol(raw_sym: str) -> str:
    """Cleans up ticker symbols and resolves market aliases."""
    if not raw_sym:
        return ""
    s = raw_sym.strip().upper()
    s = re.sub(r'-(EQ|BE|SM|ST|BZ)$', '', s).strip()
    if s in SYMBOL_ALIASES:
        return SYMBOL_ALIASES[s]
    cleaned = re.sub(r'\b(LIMITED|LTD\.?|CORP|CORPORATION|OF INDIA|HOLDINGS?)\b', '', s).strip()
    cleaned = re.sub(r'\s+', ' ', cleaned)
    return SYMBOL_ALIASES.get(cleaned, cleaned)


