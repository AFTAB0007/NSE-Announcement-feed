def download_announcement_pdf(pdf_url: str) -> str:
    """Safely downloads PDF from NSE using authenticated curl_cffi session."""
    if not pdf_url or not pdf_url.lower().endswith(".pdf"):
        return ""

    filename = pdf_url.split("/")[-1].split("?")[0]
    local_path = os.path.join(PDF_DOWNLOAD_DIR, filename)

    if os.path.exists(local_path) and os.path.getsize(local_path) > 1000:
        return local_path

    session = get_nse_session()
    if not session:
        return ""

    headers = {
        "Accept": "application/pdf,*/*",
        "Referer": "https://www.nseindia.com/",
    }

    try:
        resp = session.get(pdf_url, headers=headers, timeout=25)
        if resp.status_code == 200 and len(resp.content) > 500:
            with open(local_path, "wb") as f:
                f.write(resp.content)
            return local_path
    except Exception as e:
        log(f"⚠️ Failed to download PDF {pdf_url}: {e}")

    return ""


def extract_key_details_from_pdf(pdf_path: str) -> dict:
    """Extracts revenue, profit, and order details from digital/scanned PDFs."""
    if not pdf_path or not os.path.exists(pdf_path):
        return {}

    extracted_text = ""
    tables = []

    try:
        with pdfplumber.open(pdf_path) as pdf:
            # Process up to 5 initial pages for speed and relevance
            pages_to_read = pdf.pages[:5]
            for p_idx, page in enumerate(pages_to_read):
                txt = page.extract_text() or ""
                extracted_text += f"\n {txt}"
                tbls = page.extract_tables()
                if tbls:
                    for t in tbls:
                        if t and len(t) > 1:
                            tables.append(t)
    except Exception as e:
        log(f"⚠️ pdfplumber error on {pdf_path}: {e}")

    # Fallback to OCR if PDF is purely scanned
    if len(extracted_text.strip()) < 80 and OCR_AVAILABLE:
        try:
            images = convert_from_path(pdf_path, first_page=1, last_page=2)
            for img in images:
                extracted_text += "\n" + pytesseract.image_to_string(img)
        except Exception as ocr_err:
            log(f"⚠️ OCR execution failed on {pdf_path}: {ocr_err}")

    details = {}

    # Check for order win / contract details
    order_val = re.search(
        r"(?:order|contract|worth|valued at|bagged|awarded)[\s\w:]*(?:Rs\.?|INR|USD|\$)?\s*([0-9,.]+\s*(?:crore|cr|lakh|million|billion)?)",
        extracted_text,
        re.I
    )
    if order_val:
        matched_val = order_val.group(1).strip()
        if re.search(r"\d", matched_val):
            details["Order / Deal Value"] = matched_val

    # Check tables for Revenue and PAT
    for tbl in tables:
        for row in tbl:
            row_str = " ".join([str(c) for c in row if c]).lower()
            nums = re.findall(r'\(?-?\b\d{1,3}(?:,\d{3})*(?:\.\d+)?\)?', row_str)
            nums = [n for n in nums if not re.match(r'^\(?[0-9a-zA-Z]{1,2}\)?$', n)]

            if not nums:
                continue

            if ("revenue from operations" in row_str or "total income" in row_str) and "Revenue" not in details:
                details["Revenue"] = nums[0]
                if len(nums) > 1:
                    details["Revenue (Prev Qtr)"] = nums[1]

            if any(term in row_str for term in ["profit for the period", "net profit after tax", "profit/(loss) for the period"]) and "PAT (Net Profit)" not in details:
                details["PAT (Net Profit)"] = nums[0]
                if len(nums) > 1:
                    details["PAT (Prev Qtr)"] = nums[1]

    # Text regex fallback if tables yielded empty results
    if "Revenue" not in details:
        rev_m = re.search(r"(?:Revenue from operations|Total Income)[\s:]*([0-9,.]+)", extracted_text, re.I)
        if rev_m:
            details["Revenue"] = rev_m.group(1).strip()

    if "PAT (Net Profit)" not in details:
        pat_m = re.search(r"(?:Net Profit(?: after tax)?|Profit for the period)[\s:\w]*[\s:]+([0-9,.\(\)-]+)", extracted_text, re.I)
        if pat_m:
            details["PAT (Net Profit)"] = pat_m.group(1).strip()

    return details


